using Modulus.AspNetCore.Hosting;
using Xunit;

namespace Modulus.AspNetCore.Hosting.Tests;

/// <summary>The Content-Security-Policy the pages send, the nonce, and the hardening defaults.</summary>
public class HostingTests
{
    [Fact]
    public void ThePolicy_CarriesTheNonceAndRefusesInlineScripts()
    {
        var policy = HostingExtensions.PolicyFor(new ModulusHardeningOptions(), "abc123");

        Assert.Contains("script-src 'self' 'nonce-abc123' 'unsafe-eval'", policy);
        Assert.DoesNotContain("script-src 'self' 'unsafe-inline'", policy);
        Assert.Contains("object-src 'none'", policy);
        Assert.Contains("frame-ancestors 'self'", policy);
        Assert.DoesNotContain("report-uri", policy);
    }

    [Fact]
    public void ThePolicy_AddsTheConnectSourcesAndTheReportUri()
    {
        var options = new ModulusHardeningOptions { CspReportUri = "/csp-report" };
        options.ConnectSources.Add("https://tiles.example.com");

        var policy = HostingExtensions.PolicyFor(options, "n");

        Assert.Contains("connect-src 'self' ws: wss: https: https://tiles.example.com;", policy);
        Assert.EndsWith("; report-uri /csp-report", policy);
    }

    [Fact]
    public void ANonceIsEmptyWhenHardeningHasNotRun()
    {
        // The nonce is generated by the middleware (base64, 16 bytes); a page with no request has none.
        Assert.Equal("", CspNonce.Of(new Microsoft.AspNetCore.Http.DefaultHttpContext()));
    }

    [Fact]
    public void TheDefaults_CompressAndSendTheHeadersButReportTheCsp()
    {
        var options = new ModulusHardeningOptions();

        Assert.True(options.Compression);
        Assert.True(options.SecurityHeaders);
        Assert.True(options.ContentSecurityPolicy);
        Assert.False(options.CspEnforce);
    }
}
