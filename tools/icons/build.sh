#!/usr/bin/env bash
# Regenerates src/Modulus.Ui.Abstractions/Shell/ExtraIconSvg.g.cs: the icons the AntDesign package does not ship.
# Ant Design icons newer than the package (ANT_EXTRA) come from @ant-design/icons-svg; the "ri:" icons listed in
# remix.txt from Remix Icon. Needs python3 and network access.
set -euo pipefail
ANT_VERSION=4.4.2
REMIX_VERSION=4.9.1
here="$(cd "$(dirname "$0")" && pwd)"
root="$here/../.."
python3 - "$root" "$ANT_VERSION" "$REMIX_VERSION" <<'PY'
import json, re, sys, urllib.parse, urllib.request
root, ant_version, remix_version = sys.argv[1:4]
# Ant Design outline icons the pages use that AntDesign's bundled set lacks.
ANT_EXTRA = ["moon", "product", "signature", "sun", "truck", "x"]

def get(url):
    return urllib.request.urlopen(url).read().decode()

remix = sorted({l.strip() for l in open(f"{root}/tools/icons/remix.txt", encoding="utf-8") if l.strip() and not l.startswith("#")})

files = json.loads(get(f"https://data.jsdelivr.com/v1/package/npm/remixicon@{remix_version}/flat"))["files"]
paths = {}
for f in (x["name"] for x in files if x["name"].startswith("/icons/") and x["name"].endswith(".svg")):
    base = f.rsplit("/", 1)[1][:-4]
    if base.endswith("-line"): paths[base[:-5]] = f           # outline style, like Ant Design's
    elif not base.endswith("-fill"): paths.setdefault(base, f)  # Editor icons have a single style

def body(svg):
    view_box = re.search(r'viewBox="([^"]+)"', svg).group(1)
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    inner = re.sub(r'\s+', ' ', inner).strip()
    return f'<svg viewBox="{view_box}">{inner}</svg>'

entries, missing = [], []
for n in ANT_EXTRA:
    entries.append((n, body(get(f"https://cdn.jsdelivr.net/npm/@ant-design/icons-svg@{ant_version}/inline-svg/outlined/{n}.svg"))))
for n in remix:
    if n not in paths: missing.append(n); continue
    entries.append(("ri:" + n, body(get(f"https://cdn.jsdelivr.net/npm/remixicon@{remix_version}{urllib.parse.quote(paths[n])}"))))

out = [
    "// <auto-generated> by tools/icons/build.sh — do not edit. </auto-generated>",
    f"// Ant Design icons: @ant-design/icons-svg {ant_version} (MIT License, Copyright (c) 2018-present Ant UED).",
    f"// Remix Icon {remix_version} (Apache License 2.0, https://remixicon.com).",
    "namespace Modulus.Ui.Abstractions.Shell;",
    "",
    "/// <summary>SVGs of the icons <see cref=\"ShellRenderer.Icon\"/> draws that the AntDesign package does not ship.</summary>",
    "public static class ExtraIconSvg",
    "{",
    "    public static readonly IReadOnlyDictionary<string, string> Svgs = new Dictionary<string, string>(StringComparer.Ordinal)",
    "    {",
]
out += [f'        ["{k}"] = """{v}""",' for k, v in entries]
out += ["    };", "}", ""]
dest = f"{root}/src/Modulus.Ui.Abstractions/Shell/ExtraIconSvg.g.cs"
open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"{len(entries)} icons written to {dest}")
if missing: print("missing:", ", ".join(missing)); sys.exit(1)
PY
